const fs = require('node:fs');
const vm = require('node:vm');
const sharp = require(process.env.PMD_SHARP_MODULE || 'sharp');
const window = {PMD_BOUNDS_DATA: {}};
const sources = ['assets/pmd/anim-data.js', ...['sinnoh/pmd-data','unova/pmd-data','mega/pmd-data','mega/padventures-data'].map(p => 'modes/idle/'+p+'.js')];
for (const file of sources) vm.runInNewContext(fs.readFileSync(file, 'utf8'), {window});
Object.assign(window.PMD_ANIM_DATA, window.IDLE_UNOVA_PMD);
const tag = (xml, name) => xml?.match(new RegExp('<'+name+'>([^<]+)</'+name+'>'))?.[1];

async function thumbnail(key, xml) {
  const animations = new Map([...xml.matchAll(/<Anim>([\s\S]*?)<\/Anim>/g)].map(([, anim]) => [tag(anim, 'Name'), anim]));
  let pose = animations.get('Idle') || animations.get('Walk');
  for (let depth = 0; tag(pose, 'CopyOf') && depth < 8; depth++) pose = animations.get(tag(pose, 'CopyOf'));
  const width = Number(tag(pose, 'FrameWidth')), height = Number(tag(pose, 'FrameHeight'));
  const dir = key.replace(/s$/, key.includes('/') ? '/0001' : '/0000/0001');
  const file = 'assets/pmd/sprite/'+dir+'/'+tag(pose, 'Name')+'-Anim.png';
  if (!width || !height || !fs.existsSync(file)) return null;
  const frame = await sharp(file).extract({left:0, top:0, width, height}).png().toBuffer();
  return (await sharp(frame).trim({background:'#00000000', threshold:0}).webp({lossless:true}).toBuffer()).toString('base64');
}

(async () => {
  const entries = Object.entries(window.PMD_ANIM_DATA).sort(([a],[b]) => a.localeCompare(b));
  const rows = [];
  for (let i = 0; i < entries.length; i += 16) {
    const batch = await Promise.all(entries.slice(i,i+16).map(async ([key, xml]) => [key, await thumbnail(key,xml)]));
    rows.push(...batch.filter(([, data]) => data));
  }
  fs.writeFileSync('modes/idle/pmd-thumbnails-data.js', '/* Generated by scripts/build-pmd-thumbnails.cjs from local Mystery Dungeon sheets. */\nwindow.IDLE_PMD_THUMBNAILS={\n'+rows.map(([key, data]) => JSON.stringify(key)+':'+JSON.stringify(data)).join(',\n')+'\n};\n');
  console.log('PMD thumbnails:', rows.length);
})().catch(error => {console.error(error);process.exitCode=1});
