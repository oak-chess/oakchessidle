import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context={window:{}};vm.runInNewContext(fs.readFileSync('modes/idle/online/hunt-presentation.js','utf8'),context);
const units=[{x:400,y:300,maxHp:100,alive:true,el:{style:{left:'400px',top:'300px'}}},{x:600,y:250,maxHp:200,alive:true,el:{style:{}}}];
const events=[];const view=context.window.createHuntPresentation({units:()=>units,update:u=>u.el.style.transform=`translate(${u.x}px,${u.y}px)`,attack:()=>events.push('attack'),cast:()=>events.push('cast'),hit:()=>events.push('hit'),heal:()=>events.push('heal'),faint:()=>events.push('faint')});
view.frame({t:500,u:[[400,300,500,1,0,-1,1,1,5,1,20,10,0,0,0,0,0],[600,250,750,1,1,1,0,0,2,1,30,0,0,0,0,0,0]]},[{k:'attack',a:0,b:1},{k:'cast',a:1,b:0,m:0},{k:'hit',a:1,b:0,n:50}]);
assert.equal(units[0].el.style.left,'');assert.equal(units[0].el.style.top,'');
assert.equal(units[0].el.style.transform,'translate(400px,300px)');
assert.equal(units[0].hp,50);assert.equal(units[1].hp,150);
assert.equal(units[1].el.style.transform,'translate(600px,250px)');
assert.equal(units[0].fa,-1);assert.equal(units[0].moving,true);assert.equal(units[0].target,units[1]);assert.equal(units[0].shield,10);
assert.deepEqual(events,['attack','cast','hit']);
view.frame({t:600,u:[[410,310,0,0,0],[600,250,750,1,1]]});assert.equal(events.at(-1),'faint');
view.frame({t:700,u:[[410,310,0,0,0],[600,250,750,1,1]]});assert.equal(events.filter(e=>e==='faint').length,1);
console.log('PASS replay position, directions, movement, targets, visual events and one-time faint');
